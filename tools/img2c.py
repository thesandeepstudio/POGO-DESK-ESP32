#!/usr/bin/env python3
"""Convert a webp/png image into a monochrome (1bpp) C header for the TFT.

Bright pixels (white) are drawn on screen; dark pixels are treated as
transparent and are simply not drawn. The image is aspect-fitted to a canvas
(maxW x maxH) and centered. Output is MSB-first bit-packed rows + x/y offset.

Usage: python tools/img2c.py assets/images/spider.webp src/spider_bitmap.h \
       --maxw 280 --maxh 240 --threshold 128 --name SPIDER
"""
import argparse
import sys
from PIL import Image


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("output")
    ap.add_argument("--maxw", type=int, default=280)
    ap.add_argument("--maxh", type=int, default=240)
    ap.add_argument("--threshold", type=int, default=128,
                    help="luminance >= threshold is drawn (white)")
    ap.add_argument("--name", default="IMG")
    ap.add_argument("--invert", action="store_true")
    ap.add_argument("--mode", default="mono",
                    choices=["mono", "rgb565"],
                    help="mono = 1bpp white/dark; rgb565 = full-color packed")
    args = ap.parse_args()

    im = Image.open(args.input).convert("RGB")

    # Keep the full image if it already fits; exact-fit prefix images to the
    # canvas (they get centered at the offset below).
    w, h = im.size
    scale = min(args.maxw / w, args.maxh / h)
    if scale >= 1.0:
        scale = 1.0  # never upscale
    nw = max(1, round(w * scale))
    nh = max(1, round(h * scale))
    im = im.resize((nw, nh), Image.LANCZOS)

    ox = (args.maxw - nw) // 2
    oy = (args.maxh - nh) // 2
    px = list(im.getdata())

    out = []
    out.append(f"// Generated by tools/img2c.py from {args.input}")
    out.append(f"// {w}x{h} -> {nw}x{nh}, offset x={ox} y={oy} (mode={args.mode})")
    out.append(f"#define {args.name}_W {nw}")
    out.append(f"#define {args.name}_H {nh}")
    out.append(f"#define {args.name}_X {ox}")
    out.append(f"#define {args.name}_Y {oy}")

    if args.mode == "mono":
        bits = []
        for r, g, b in px:
            lum = 0.299 * r + 0.587 * g + 0.114 * b
            bit = 1 if lum >= args.threshold else 0
            if args.invert:
                bit = 1 - bit
            bits.append(bit)
        row_bytes = (nw + 7) // 8
        out.append(f"static const size_t {args.name}_STRIDE = {row_bytes};")
        out.append(f"const uint8_t {args.name}_BITS[{row_bytes * nh}] PROGMEM = {{")
        for y in range(nh):
            row = bits[y * nw:(y + 1) * nw]
            row += [0] * (row_bytes * 8 - len(row))
            bytes_ = []
            for b in range(row_bytes):
                byte = 0
                for bit in range(8):
                    if row[b * 8 + bit]:
                        byte |= 1 << (7 - bit)
                bytes_.append(byte)
            out.append("  " + ",".join(f"0x{b:02x}" for b in bytes_) + ",")
        out.append("};")
    else:
        # RGB565 big-endian packed
        out.append(f"const uint16_t {args.name}_RGB[{nw * nh}] PROGMEM = {{")
        for y in range(nh):
            vals = []
            for x in range(nw):
                r, g, b = px[y * nw + x]
                c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
                vals.append(f"0x{c:04x}")
            out.append("  " + ",".join(vals) + ",")
        out.append("};")
    out.append("")

    with open(args.output, "w", newline="\n") as f:
        f.write("\n".join(out))

    bytes_ = (nw * nh * 2) if args.mode == "rgb565" else ((nw + 7) // 8 * nh)
    print(f"wrote {args.output}: {nw}x{nh}, {bytes_} bytes, "
          f"offset ({ox},{oy})")


if __name__ == "__main__":
    sys.exit(main())